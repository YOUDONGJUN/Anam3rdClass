-- 3교시 톡방: 참여자끼리 주고받는 글·사진
create table chat_messages (
    id         bigint generated by default as identity primary key,
    meetup_id  bigint not null references meetups (id) on delete cascade,
    member_id  bigint not null references members (id) on delete cascade,
    -- 글 (사진만 보낸 메시지는 null)
    body       varchar(1000),
    created_at timestamp with time zone not null,
    -- 보낸 사람이 지운 시각 (자리는 남기고 "지운 메시지"로 보인다)
    deleted_at timestamp with time zone
);
create index idx_chat_messages_meetup on chat_messages (meetup_id, id);
create index idx_chat_messages_member on chat_messages (member_id, created_at);

-- 톡방 사진. 저장소의 chat/ 아래에 두고, 올린 날부터 30일 뒤 저장소가 지운다 (R2 수명 규칙)
create table chat_photos (
    id          bigint generated by default as identity primary key,
    message_id  bigint not null references chat_messages (id) on delete cascade,
    storage_key varchar(200) not null,
    position    int not null,
    constraint uq_chat_photos_key unique (storage_key)
);
create index idx_chat_photos_message on chat_photos (message_id);

-- 톡방마다 한 사람의 상태: 어디까지 읽었는지, 알림을 껐는지
create table chat_states (
    id           bigint generated by default as identity primary key,
    meetup_id    bigint not null references meetups (id) on delete cascade,
    member_id    bigint not null references members (id) on delete cascade,
    last_read_id bigint not null default 0,
    muted        boolean not null default false,
    constraint uq_chat_states unique (meetup_id, member_id)
);
create index idx_chat_states_member on chat_states (member_id);

-- 추억: 모였던 3교시에서 찍은 사진(인생네컷 등)과 한 줄. 계속 보관한다
create table memories (
    id         bigint generated by default as identity primary key,
    meetup_id  bigint not null references meetups (id) on delete cascade,
    member_id  bigint not null references members (id) on delete cascade,
    caption    varchar(200),
    -- PARTICIPANTS: 함께한 사람만 · PUBLIC: 그 3교시를 볼 수 있는 원우 모두
    visibility varchar(20) not null,
    created_at timestamp with time zone not null
);
create index idx_memories_meetup on memories (meetup_id);
create index idx_memories_created on memories (created_at);

create table memory_photos (
    id          bigint generated by default as identity primary key,
    memory_id   bigint not null references memories (id) on delete cascade,
    storage_key varchar(200) not null,
    position    int not null,
    constraint uq_memory_photos_key unique (storage_key)
);
create index idx_memory_photos_memory on memory_photos (memory_id);
