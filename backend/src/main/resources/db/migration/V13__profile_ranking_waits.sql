-- 빈자리 대기: 정원이 찬 3교시에 "자리 나면 알림"을 신청한 사람. 자리가 나면 모두에게 알리고, 먼저 참여한 사람이 탄다
-- 참여하거나 신청을 취소하면 지운다. 3교시가 끝나면 화면에서 보이지 않는다
create table meetup_waits (
    id          bigint generated by default as identity primary key,
    meetup_id   bigint not null references meetups (id),
    member_id   bigint not null references members (id),
    created_at  timestamp with time zone not null,
    constraint uk_meetup_wait unique (meetup_id, member_id)
);

create index idx_meetup_waits_member on meetup_waits (member_id);
