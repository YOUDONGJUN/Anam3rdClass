-- 송금 링크 (선택): 토스 아이디, 카카오페이 송금 링크. 정산할 때 함께한 원우에게만 보이고, 탈퇴하면 지운다
alter table members add column toss_id varchar(30);
alter table members add column kakaopay_url varchar(100);

-- 정산: 3교시 하나에 하나. 계산한 사람(참여자 누구든)이 총액을 넣으면 1인 금액(100원 단위 올림)을 나머지에게 요청한다.
-- 돈은 서비스가 받지 않는다 — 송금은 각자 토스·카카오페이 앱에서 한다
create table settlements (
    id               bigint generated by default as identity primary key,
    meetup_id        bigint  not null references meetups (id),
    payer_id         bigint  not null references members (id),
    total            integer not null,
    per_person       integer not null,
    created_at       timestamp with time zone not null,
    updated_at       timestamp with time zone not null,
    -- 마지막으로 정산 요청·다시 알리기를 한 시각 (다시 알리기는 하루 한 번)
    reminded_at      timestamp with time zone not null,
    -- 모두 보낸 시각 (누가 보냄을 취소하면 다시 비운다)
    done_at          timestamp with time zone,
    -- 밤(한국 시간 0~8시)이라 아침 8시로 미룬 알림: 요청·다시 알리기 / 정산 끝
    request_pending  boolean not null default false,
    done_pending     boolean not null default false,
    constraint uk_settlement_meetup unique (meetup_id)
);

-- 정산에서 한 사람 몫 (계산한 사람은 빼고). sent_at 이 비어 있으면 아직 안 보냄
create table settlement_shares (
    id             bigint generated by default as identity primary key,
    settlement_id  bigint not null references settlements (id),
    member_id      bigint not null references members (id),
    sent_at        timestamp with time zone,
    constraint uk_settlement_share unique (settlement_id, member_id)
);

create index idx_settlement_shares_member on settlement_shares (member_id);
