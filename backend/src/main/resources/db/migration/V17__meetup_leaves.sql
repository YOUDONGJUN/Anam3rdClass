-- 성사된 3교시에서 나간 기록. 참여했다 바로 나가며 실명·단톡방 링크를 모으는 것을 막는다:
-- 최근 30일 동안 성사된 3교시에서 3번 나가면, 한동안 이미 성사된 3교시에는 참여할 수 없다. 30일이 지나면 지운다
create table meetup_leaves (
    id         bigint generated by default as identity primary key,
    member_id  bigint not null references members (id) on delete cascade,
    meetup_id  bigint not null references meetups (id) on delete cascade,
    left_at    timestamp with time zone not null
);

create index idx_meetup_leaves_member on meetup_leaves (member_id, left_at);
create index idx_meetup_leaves_meetup on meetup_leaves (meetup_id);
create index idx_meetup_leaves_left on meetup_leaves (left_at);
