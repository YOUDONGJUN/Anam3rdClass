package com.anam3.meetup;

/**
 * 번개 상태는 DB 에 저장하지 않고 "지금 시각 + 참여 인원"으로 그때그때 계산한다.
 * (무료 서버는 잠들 수 있어서 정해진 시각에 도는 배치 작업에 기대지 않기 위함)
 */
public enum MeetupStatus {
    /** 모집 중 (최소 인원 미달, 마감 전) */
    RECRUITING,
    /** 성사! 최소 인원 달성 (정원 전이고 마감 전이면 추가 참여 가능) */
    CONFIRMED,
    /** 마감까지 최소 인원 미달 → 조용히 무산 */
    FAILED,
    /** 성사된 번개의 모임 시간이 지남 */
    DONE,
    /** 개설자 또는 운영자가 취소 */
    CANCELED
}
