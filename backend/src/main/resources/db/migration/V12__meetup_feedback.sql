-- 3교시 후기: 성사된 3교시가 끝난 다음 날부터 7일 동안, 앱을 열면 참여자에게 한 번 묻는다
-- 한 사람이 한 3교시에 한 줄. 답하지 않고 닫으면 met 이 비어 있는 줄이 남는다 (다시 묻지 않는다)
create table meetup_feedbacks (
    id          bigint generated by default as identity primary key,
    meetup_id   bigint      not null references meetups (id),
    member_id   bigint      not null references members (id),
    -- 실제로 모였는지 (비어 있으면 답하지 않고 닫음)
    met         boolean,
    -- 모였을 때만: GOOD(좋았어요) · OK(괜찮았어요) · BAD(아쉬웠어요)
    rating      varchar(10),
    created_at  timestamp with time zone not null,
    answered_at timestamp with time zone,
    constraint uk_meetup_feedback unique (meetup_id, member_id)
);

create index idx_meetup_feedbacks_member on meetup_feedbacks (member_id);

-- 후기에서 '아쉬웠어요'를 고른 뒤 한 신고 (대학원장의 신고 목록·통계에서만 표시한다)
alter table reports add column from_feedback boolean not null default false;
