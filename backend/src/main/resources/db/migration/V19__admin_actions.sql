-- 관리자 조치 기록: 교수·대학원장이 한 일(이용 정지·직책·정보 고치기·탈퇴시키기·3교시·공지 지우기·신고 처리·학교 정보)을
-- 남겨 대학원장이 관리 화면 '기록'에서 본다. 사람은 번호로만 남긴다 — 탈퇴하면 이름이 지워져 "탈퇴한 원우"로 보인다.
-- 3교시는 지워져도 기록이 남도록 외래 키 없이 번호만 둔다 (제목은 detail 에)
create table admin_actions (
    id                bigint generated by default as identity primary key,
    actor_id          bigint       not null references members (id),
    -- 그때 직책 (나중에 해임돼도 '교수'로 보이게)
    actor_role        varchar(10)  not null,
    target_member_id  bigint       references members (id),
    target_meetup_id  bigint,
    action            varchar(30)  not null,
    detail            varchar(300),
    created_at        timestamp with time zone not null
);

create index idx_admin_actions_created on admin_actions (created_at);
