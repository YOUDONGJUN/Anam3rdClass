-- 제재: 교수·대학원장이 주는 경고가 쌓이면 단계가 올라간다 (1번째 경고 · 2번째 7일 정지 · 3번째 30일 정지 · 4번째 영구 정지).
-- 영구 정지는 지금처럼 members.status = BANNED, 기간 정지는 members.suspended_until 까지 (지나면 저절로 풀린다).
-- 신고만으로는 제재하지 않는다 — 사람이 확인하고 준다
alter table members add column suspended_until timestamp with time zone;

create table member_sanctions (
    id               bigint generated by default as identity primary key,
    member_id        bigint       not null references members (id),
    -- WARNING · SUSPEND_7 · SUSPEND_30 · BAN
    kind             varchar(12)  not null,
    -- 신고 이유와 같은 이름 (SPAM · ABUSE …)
    reason           varchar(20)  not null,
    -- 당사자에게 보이는 설명 (선택)
    note             varchar(300),
    -- 이 신고를 보고 줬으면 그 신고 (신고 기록은 지우지 않는다)
    report_id        bigint       references reports (id),
    actor_id         bigint       not null references members (id),
    created_at       timestamp with time zone not null,
    -- 기간 정지가 끝나는 때
    ends_at          timestamp with time zone,
    -- 당사자가 경고 창에서 확인한 때
    acknowledged_at  timestamp with time zone,
    -- 잘못 줘서 취소했으면 그때와 취소한 사람 (단계에 세지 않는다)
    revoked_at       timestamp with time zone,
    revoked_by       bigint       references members (id)
);

create index idx_member_sanctions_member on member_sanctions (member_id, created_at);
