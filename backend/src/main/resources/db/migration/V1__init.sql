-- 안암3교시 초기 스키마
-- ⚠️ 이미 배포된 마이그레이션 파일은 절대 수정하지 말고, V2__설명.sql 처럼 새 파일을 추가하세요.
-- PostgreSQL(운영)과 H2 PostgreSQL 모드(로컬/테스트) 양쪽에서 돌아가는 문법만 사용합니다.

create table members (
    id              bigint generated by default as identity primary key,
    login_id        varchar(30)  not null unique,
    password_hash   varchar(100) not null,
    name            varchar(20)  not null,
    admission_year  integer      not null,
    role            varchar(10)  not null,
    status          varchar(10)  not null,
    created_at      timestamp with time zone not null
);

create table meetups (
    id                 bigint generated by default as identity primary key,
    host_id            bigint       not null references members (id),
    title              varchar(40)  not null,
    description        varchar(500) not null,
    place              varchar(60)  not null,
    category           varchar(20)  not null,
    meet_at            timestamp with time zone not null,
    deadline_at        timestamp with time zone not null,
    min_people         integer      not null,
    max_people         integer      not null,
    participant_count  integer      not null,
    open_chat_url      varchar(300),
    canceled           boolean      not null default false,
    created_at         timestamp with time zone not null,
    updated_at         timestamp with time zone not null
);

create index idx_meetups_meet_at on meetups (meet_at);

create table participations (
    id          bigint generated by default as identity primary key,
    meetup_id   bigint not null references meetups (id) on delete cascade,
    member_id   bigint not null references members (id),
    created_at  timestamp with time zone not null,
    constraint uk_participation unique (meetup_id, member_id)
);

create index idx_participations_member on participations (member_id);

create table notices (
    id          bigint generated by default as identity primary key,
    author_id   bigint        not null references members (id),
    title       varchar(60)   not null,
    content     varchar(3000) not null,
    pinned      boolean       not null default false,
    created_at  timestamp with time zone not null,
    updated_at  timestamp with time zone not null
);

create table app_settings (
    setting_key    varchar(50)  primary key,
    setting_value  varchar(200) not null
);
