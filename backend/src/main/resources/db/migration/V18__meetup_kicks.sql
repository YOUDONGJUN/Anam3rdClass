-- 연 사람(·그 학교 교수·대학원장)이 내보낸 참여자. 같은 3교시에는 다시 참여하거나 빈자리를 기다릴 수 없다
create table meetup_kicks (
    id         bigint generated by default as identity primary key,
    meetup_id  bigint not null references meetups (id) on delete cascade,
    member_id  bigint not null references members (id) on delete cascade,
    kicked_at  timestamp with time zone not null,
    constraint uq_meetup_kicks unique (meetup_id, member_id)
);
