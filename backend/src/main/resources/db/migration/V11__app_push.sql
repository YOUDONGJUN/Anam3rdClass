-- 앱 푸시 알림
-- 앱을 설치한 기기의 푸시 토큰 (한 사람이 폰 여러 대를 쓸 수 있다. 같은 폰에서 다른 사람이 로그인하면 그 사람 것으로 바뀐다)
create table push_devices (
    id            bigint generated by default as identity primary key,
    member_id     bigint       not null references members (id) on delete cascade,
    token         varchar(512) not null,
    platform      varchar(10)  not null,
    created_at    timestamp with time zone not null,
    last_seen_at  timestamp with time zone not null,
    constraint uk_push_devices_token unique (token)
);

create index idx_push_devices_member on push_devices (member_id);

-- 끈 알림 종류 (쉼표로 구분, 비어 있으면 모두 받는다. 예: NOTICE,FEDERATION)
alter table members add column push_off varchar(100);

-- 모집 마감 30분 전 알림을 보낸 시각 (시간을 바꾸면 다시 비운다)
alter table meetups add column deadline_reminded_at timestamp with time zone;

-- 로그인 토큰 버전: 비밀번호를 정하거나 바꾸면 1 올려서, 다른 기기에 남은 예전 로그인 토큰을 끊는다
alter table members add column token_version integer not null default 0;
