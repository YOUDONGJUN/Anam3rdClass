-- 알림함: 앱 푸시를 보낼 때 한 사람 몫씩 남겨서 웹에서도 본다 (기기가 없어도, 푸시를 꺼도 담는다).
-- 내 3교시·참여한 3교시 알림만 담고, 학교 전체에 가는 알림(새 3교시·새 공지)은 담지 않는다 (피드·공지에서 보인다).
-- 30일이 지나면 지운다. 같은 tag 의 안 읽은 알림은 한 줄을 새 내용으로 바꾼다 (참여 알림이 쌓이지 않게)
create table notifications (
    id          bigint generated by default as identity primary key,
    member_id   bigint       not null references members (id),
    type        varchar(20)  not null,
    title       varchar(100) not null,
    body        varchar(300) not null,
    -- 누르면 여는 화면 (예: /meetups/12)
    path        varchar(200) not null,
    tag         varchar(100),
    created_at  timestamp with time zone not null,
    -- 알림함을 열어 본 때 (비어 있으면 안 읽음)
    read_at     timestamp with time zone
);

create index idx_notifications_member on notifications (member_id, created_at);
create index idx_notifications_created on notifications (created_at);
create index idx_notifications_path on notifications (path);
