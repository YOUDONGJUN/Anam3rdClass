-- 1) 가입할 수 있는 학교와 이메일 도메인 (지금은 고려대만. 대학원장이 관리 화면에서 추가한다)
-- 2) 회원에 카카오 회원번호, 인증된 학교 이메일, 학교를 붙인다
--    예전 회원은 처음 카카오로 로그인하고 학교 이메일을 인증할 때 이어진다 (관리자가 이메일을 미리 넣어 둔다)
-- 3) 아이디·비밀번호 칸은 더 쓰지 않는다. 안전하게 넘어간 뒤 다음 마이그레이션에서 지운다
-- 4) 이메일 인증코드 (해시로만 저장)

create table schools (
    id            bigint generated by default as identity primary key,
    name          varchar(40) not null,
    email_domain  varchar(60) not null unique,
    created_at    timestamp with time zone not null
);

