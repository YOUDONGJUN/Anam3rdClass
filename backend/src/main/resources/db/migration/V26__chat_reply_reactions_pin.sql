-- 톡방: 답장 · 공감 · 톡방 공지

-- 답장: 어느 메시지에 답했는지 (원래 메시지가 지워지면 화면에 "지운 메시지예요"로 보인다)
alter table chat_messages add column reply_to_id bigint references chat_messages (id) on delete set null;

-- 톡방 공지: 연 사람이 이 메시지를 톡방 위에 올린 시각 (톡방마다 하나 — 새로 올리면 앞의 것은 내려간다)
alter table chat_messages add column pinned_at timestamp with time zone;

-- 공감: 메시지마다 한 사람이 하나 (HEART · LIKE · CHECK · LOL · WOW · SAD). 다른 것을 누르면 바뀐다
create table chat_reactions (
    id         bigint generated by default as identity primary key,
    message_id bigint      not null references chat_messages (id) on delete cascade,
    member_id  bigint      not null references members (id) on delete cascade,
    reaction   varchar(10) not null,
    created_at timestamp with time zone not null,
    constraint uq_chat_reactions unique (message_id, member_id)
);
create index idx_chat_reactions_message on chat_reactions (message_id);
create index idx_chat_reactions_member on chat_reactions (member_id);
