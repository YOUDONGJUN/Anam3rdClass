-- IT연합회 5개 학교로 넓힌다: 고려대 · 연세대 · 성균관대 · 서강대 · 한양대
-- 1) 학교: 테마 코드(화면 색), 짧은 이름(배지), 대학원 이름, 학교별 최신 기수, 순서
-- 2) 학교 이메일 도메인을 학교마다 여러 개 둘 수 있게 따로 뺀다 (예: 성균관대 g.skku.edu, skku.edu)
-- 3) 학과: 코드에 박혀 있던 고려대 3개 학과 → 학교별 학과 표 (대학원장이 관리 화면에서 고친다)
--    한 학교에 특수대학원이 둘 이상이면 학과에 대학원 이름을 따로 적는다 (예: 연세대 공학대학원 인공지능전공)
-- 4) 3교시·공지: 학교를 붙인다. 3교시는 "연합(모든 학교)"으로도 열 수 있다
-- 5) 안전: 약관 동의 시각, 회원 탈퇴, 신고, 차단
-- 고려대 말고 다른 학교의 학과·최신 기수는 공개 자료로 넣은 임시값이다. 대학원장이 관리 화면에서 고친다.

