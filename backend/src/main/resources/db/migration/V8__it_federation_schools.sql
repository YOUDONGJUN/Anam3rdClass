-- ---------------- 4. 3교시 · 공지 ----------------

-- 3교시는 연 사람의 학교에 속한다. federated = true 면 연합 3교시 — 다섯 학교 누구나 보고 참여한다
alter table meetups add column school_id bigint;
update meetups set school_id = (select m.school_id from members m where m.id = meetups.host_id);
alter table meetups alter column school_id set not null;
alter table meetups add constraint fk_meetups_school foreign key (school_id) references schools (id);
alter table meetups add column federated boolean not null default false;
create index idx_meetups_school on meetups (school_id, meet_at);

-- 공지도 학교별. school_id 가 null 이면 연합 공지 (대학원장만 쓴다)
alter table notices add column school_id bigint;
update notices set school_id = (select m.school_id from members m where m.id = notices.author_id);
alter table notices add constraint fk_notices_school foreign key (school_id) references schools (id);

-- ---------------- 5. 신고 · 차단 ----------------

-- 신고: 3교시(meetup_id), 공지(notice_id), 사람(member_id). 사람 신고는 어느 3교시에서 했는지도 남긴다
-- school_id 는 신고 대상의 학교 — 교수는 자기 학교 신고만 본다
create table reports (
    id              bigint generated by default as identity primary key,
    reporter_id     bigint      not null references members (id),
    target_type     varchar(10) not null,
    meetup_id       bigint references meetups (id),
    notice_id       bigint references notices (id) on delete set null,
    member_id       bigint references members (id),
    school_id       bigint references schools (id),
    reason          varchar(20) not null,
    detail          varchar(500),
    -- 신고 당시 제목·내용 (글이 지워지거나 고쳐져도 확인할 수 있게)
    target_snapshot varchar(1000),
    status          varchar(10) not null,
    created_at      timestamp with time zone not null,
    resolved_at     timestamp with time zone,
    resolved_by_id  bigint references members (id)
);

create index idx_reports_status on reports (status, created_at);
create index idx_reports_reporter on reports (reporter_id, created_at);

-- 차단: 서로의 3교시가 목록에 안 보이고, 서로의 3교시에 참여할 수 없다
create table member_blocks (
    id          bigint generated by default as identity primary key,
    blocker_id  bigint not null references members (id),
    blocked_id  bigint not null references members (id),
    created_at  timestamp with time zone not null,
    constraint uk_member_block unique (blocker_id, blocked_id)
);

create index idx_member_blocks_blocked on member_blocks (blocked_id);
