-- ---------------- 회원: 학교는 꼭 있고, 학과는 학과 표를 가리킨다 ----------------

-- 학교가 비어 있는 회원은 고려대만 있던 시절의 예전 회원이다
update members set school_id = (select id from schools where code = 'KU') where school_id is null;
alter table members alter column school_id set not null;

alter table members add column department_id bigint;
alter table members add constraint fk_members_department foreign key (department_id) references departments (id);
update members
set department_id = (
    select d.id from departments d join schools s on s.id = d.school_id
    where s.code = 'KU'
      and d.short_name = case members.department
                             when 'SOFTWARE_SECURITY' then '소보'
                             when 'BIG_DATA' then '빅융'
                             when 'AI' then '인융'
                         end)
where department is not null;
alter table members drop column department;

